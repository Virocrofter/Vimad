/* ─── Helpers ─── */
export function getDemoStatus(demo) {
  if (demo.status === 'converted') return 'converted';
  if (demo.status === 'locked') return 'locked';
  if (demo.daysRemaining <= 0) return 'expired';
  if (demo.daysRemaining <= 5) return 'expiring_soon';
  return 'active';
}

export function formatCurrency(amount) {
  return new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    maximumFractionDigits: 0,
  }).format(amount);
}

export function formatDate(dateStr) {
  if (!dateStr) return '—';
  return new Date(dateStr).toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
  });
}

export function getDaysUntil(dateStr) {
  const target = new Date(dateStr);
  const now = new Date();
  const diff = Math.ceil((target - now) / (1000 * 60 * 60 * 24));
  return Math.max(0, diff);
}

export function getUsagePercent(used, total) {
  if (typeof total === 'string') return null;
  return Math.round((used / total) * 100);
}
